"""Docker Scout Adapter & Structural Normalizer (GOAL 53 - Fase 4).

Provides an optional adapter for Docker Scout CLI outputs. Ingests structured JSON/SARIF
reports generated by `docker scout cves --format sarif` or parses Scout output safely offline.
Accurately records runtime availability (e.g. CLI binary vs daemon state).
"""

from __future__ import annotations

import json
import logging
import shutil
import subprocess

from polaris.security.contracts import (
    ScannerMetadata,
    ScannerReportParseError,
    SecurityDomain,
    SecurityScannerV2,
)
from polaris.security.models import CanonicalSecurityFindingV2

logger = logging.getLogger(__name__)


class DockerScoutAdapter(SecurityScannerV2):
    """Optional adapter for Docker Scout vulnerability intelligence."""

    def __init__(self, executable_path: str | None = None) -> None:
        self._custom_executable = executable_path
        self._cached_available: bool | None = None

    @property
    def metadata(self) -> ScannerMetadata:
        return ScannerMetadata(
            scanner_id="docker_scout",
            name="Docker Scout Container & Image Vulnerability Scanner",
            version="1.21.0",
            domain=SecurityDomain.IMAGE_VULNERABILITY,
            supported_file_patterns=["*scout*.json", "*scout*.sarif", "docker-scout.json"],
            description="Ingests or executes Docker Scout vulnerability analysis for container images and filesystem artifacts.",
            external_dependencies=["docker", "docker-scout"],
            is_optional=True,
        )

    def is_available(self) -> bool:
        """Check if Docker CLI and Scout plugin are available."""
        if self._cached_available is not None:
            return self._cached_available

        docker_bin = shutil.which(self._custom_executable or "docker")
        if not docker_bin:
            self._cached_available = False
            return False

        try:
            res = subprocess.run(
                [docker_bin, "scout", "version"],
                capture_output=True,
                text=True,
                timeout=3,
            )
            self._cached_available = res.returncode == 0
        except Exception:
            self._cached_available = False

        return bool(self._cached_available)

    def check_live_auth_status(self) -> tuple[bool, str]:
        """Check if Docker Scout CLI is authenticated to Docker Hub/Scout service for live scanning."""
        docker_bin = shutil.which(self._custom_executable or "docker")
        if not docker_bin:
            return False, "Docker binary not found in PATH."
        try:
            res = subprocess.run(
                [docker_bin, "scout", "quickview", "--help"],
                capture_output=True,
                text=True,
                timeout=5,
            )
            if res.returncode != 0:
                return False, f"docker scout error: {res.stderr.strip()}"
            return True, "docker scout CLI available (requires Docker Hub login for live remote index lookups)."
        except Exception as exc:
            return False, f"Exception probing docker scout: {type(exc).__name__}"

    def scan_file(self, file_path: str, content: str) -> list[CanonicalSecurityFindingV2]:
        """Ingest pre-computed Docker Scout JSON or SARIF report deterministically.

        Raises:
            ScannerReportParseError: When a designated scout file has corrupt JSON or malformed schema,
                                     preventing silent false PASS in security evaluations.
        """
        norm_path = file_path.replace("\\", "/").lower()
        if not (norm_path.endswith(".json") or norm_path.endswith(".sarif")):
            return []

        # If file is specifically named as scout or docker-scout report, enforce valid parsing
        is_targeted_scout_file = "scout" in norm_path or "docker-scout" in norm_path

        try:
            data = json.loads(content)
        except json.JSONDecodeError as exc:
            if is_targeted_scout_file:
                raise ScannerReportParseError(
                    f"Corrupted JSON in Docker Scout report '{file_path}': {exc}",
                    file_path=file_path,
                ) from exc
            return []

        if not isinstance(data, dict):
            if is_targeted_scout_file:
                raise ScannerReportParseError(
                    f"Invalid top-level structure in Docker Scout report '{file_path}': expected JSON object.",
                    file_path=file_path,
                )
            return []

        findings: list[CanonicalSecurityFindingV2] = []

        # Check if Scout SARIF report
        if "runs" in data and isinstance(data["runs"], list):
            runs = data["runs"]
            for run in runs:
                if not isinstance(run, dict):
                    continue
                driver = run.get("tool", {}).get("driver", {})
                driver_name = str(driver.get("name", "")).lower()
                if "scout" in driver_name or "docker" in driver_name:
                    results = run.get("results", [])
                    if not isinstance(results, list):
                        raise ScannerReportParseError(
                            f"Invalid SARIF results in '{file_path}': expected array.",
                            file_path=file_path,
                        )
                    rules = {r.get("id"): r for r in driver.get("rules", []) if isinstance(r, dict)}
                    for r in results:
                        rule_id = r.get("ruleId", "UNKNOWN_CVE")
                        rule_meta = rules.get(rule_id, {})
                        msg = r.get("message", {}).get("text", "")
                        # Extract rule properties and message metadata
                        rule_props = rule_meta.get("properties", {}) if isinstance(rule_meta.get("properties"), dict) else {}
                        res_props = r.get("properties", {}) if isinstance(r.get("properties"), dict) else {}

                        # 1. Severidade: prioritize cvssV3_severity, then tags, then level, then HIGH default
                        sev = "MEDIUM"
                        if "cvssV3_severity" in rule_props:
                            sev = str(rule_props["cvssV3_severity"]).upper()
                        elif "tags" in rule_props and isinstance(rule_props["tags"], list) and rule_props["tags"]:
                            sev = str(rule_props["tags"][0]).upper()
                        elif r.get("level") == "error":
                            sev = "HIGH"
                        elif r.get("level") == "warning":
                            sev = "MEDIUM"
                        elif r.get("level") == "note":
                            sev = "LOW"

                        # 2. Package and Version extraction
                        pkg_name = res_props.get("packageName")
                        pkg_ver = res_props.get("packageVersion")
                        purl = res_props.get("purl")

                        purls_list = rule_props.get("purls", [])
                        if not purl and purls_list and isinstance(purls_list, list):
                            purl = str(purls_list[0])

                        if not pkg_name and purl:
                            # Parse pkg:apk/alpine/libxml2@2.13.9-r2?os_name=alpine
                            base_purl = purl.split("?")[0]
                            if "@" in base_purl:
                                parts = base_purl.split("@", 1)
                                pkg_name = parts[0].split("/")[-1]
                                pkg_ver = parts[1] if len(parts) > 1 else None

                        # 3. Fixed version extraction: strictly do not treat "not fixed" as a fix version
                        fixed_ver_raw = rule_props.get("fixed_version") or res_props.get("fixedVersion")
                        fixed_ver = None
                        if fixed_ver_raw and str(fixed_ver_raw).strip().lower() not in ("not fixed", "none", "unknown", ""):
                            fixed_ver = str(fixed_ver_raw).strip()

                        # 4. Score and Help text
                        cvss_score = rule_props.get("security-severity")
                        try:
                            score_val = float(cvss_score) * 10.0 if cvss_score is not None else (90.0 if sev == "CRITICAL" else 70.0)
                        except (ValueError, TypeError):
                            score_val = 90.0 if sev == "CRITICAL" else (75.0 if sev == "HIGH" else 50.0)

                        remediation = (
                            f"Upgrade package '{pkg_name}' to {fixed_ver}."
                            if fixed_ver
                            else "No upstream fix version currently available. Monitor vendor advisory or mitigate in base image."
                        )

                        findings.append(
                            CanonicalSecurityFindingV2.create(
                                scanner_id=self.metadata.scanner_id,
                                domain=SecurityDomain.IMAGE_VULNERABILITY,
                                rule_or_cve=rule_id,
                                title=f"Docker Scout: {rule_id} in {pkg_name or 'container package'}",
                                file_path=file_path,
                                line=1,
                                severity=sev,
                                confidence="HIGH",
                                evidence_text=msg or f"Identified by Docker Scout for package {pkg_name} {pkg_ver}",
                                remediation_hint=remediation,
                                component_name=pkg_name,
                                component_version=pkg_ver,
                                purl=purl,
                                cve_id=rule_id if rule_id.startswith("CVE-") else None,
                                advisory_source="docker_scout",
                                risk_score=score_val,
                            )
                        )
        return findings
